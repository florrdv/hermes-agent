"""Open a kanban card's Claude Code session in Warp (macOS).

Warp's ``warp://action/new_window?path=`` / ``new_tab`` URIs only change directory; they
cannot run a command, and Warp no longer opens legacy ``warp://launch/`` Launch Configuration
links. A Tab Config can: a TOML file under ``~/.warp/tab_configs/`` whose pane carries an
absolute ``directory`` and ``commands``, opened with ``warp://tab_config/<file stem>`` (a new
tab in the active Warp window). Hermes writes one file per task, ``hermes_<task_id>.toml``
(stem snake_case-safe), overwritten on every open.

Every TOML string is emitted with ``json.dumps``; a JSON string is a valid TOML basic string,
so paths and shell-quoted commands cannot break the document.
"""

from __future__ import annotations

import json
import re
import subprocess
from pathlib import Path
from typing import Callable, Optional, Sequence

from hermes_cli.kanban_claude_session import OpenSessionPlan

WARP_APP = "Warp.app"


class WarpUnavailable(RuntimeError):
    """Warp cannot be launched on this host (not macOS, not installed, or ``open`` failed)."""


def tab_configs_dir(home: Optional[Path] = None) -> Path:
    return (home or Path.home()) / ".warp" / "tab_configs"


def tab_config_name(task_id: str) -> str:
    """The file stem Warp addresses the config by; Warp wants it snake_case-safe."""
    return "hermes_" + re.sub(r"[^A-Za-z0-9_]", "_", task_id)


def tab_config_path(task_id: str, home: Optional[Path] = None) -> Path:
    return tab_configs_dir(home) / f"{tab_config_name(task_id)}.toml"


def tab_config_toml(plan: OpenSessionPlan, home: Optional[Path] = None) -> str:
    """One tab, one pane that runs ``plan.command`` in ``plan.cwd`` (Warp wants an absolute
    ``directory``; a plan without one opens in the user's home)."""
    q = json.dumps
    cwd = plan.cwd or str(home or Path.home())
    return "\n".join((
        f"# Generated by `hermes kanban open-session {plan.task_id}` ({plan.mode}); overwritten on every open.",
        f"name = {q(f'Hermes {plan.task_id}')}",
        f"title = {q(f'{plan.task_id} ({plan.mode})')}",
        "",
        "[[panes]]",
        'id = "claude"',
        'type = "terminal"',
        f"directory = {q(cwd)}",
        f"commands = [{q(plan.command)}]",
        "is_focused = true",
        "",
    ))


def write_tab_config(plan: OpenSessionPlan, home: Optional[Path] = None) -> Path:
    path = tab_config_path(plan.task_id, home)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(tab_config_toml(plan, home), encoding="utf-8")
    return path


def tab_config_uri(task_id: str) -> str:
    return f"warp://tab_config/{tab_config_name(task_id)}"


def warp_app_path() -> Optional[Path]:
    from hermes_platform.resolver.known_dirs import mac_application_dirs

    for base in mac_application_dirs():
        candidate = Path(base).expanduser() / WARP_APP
        if candidate.is_dir():
            return candidate
    return None


def _run_open(argv: Sequence[str]) -> bool:
    try:
        return subprocess.run(list(argv), capture_output=True, timeout=15, check=False).returncode == 0
    except (OSError, subprocess.SubprocessError):
        return False


def launch_in_warp(plan: OpenSessionPlan, *, opener: Callable[[Sequence[str]], bool] = _run_open,
                   home: Optional[Path] = None) -> Path:
    """Write the task's tab config and ask macOS to open it in Warp; returns the config
    path. ``opener(argv) -> ok`` is the only process boundary (tests inject it)."""
    from hermes_platform.host.facts import os_family
    from hermes_platform.resolver import locate_command

    if os_family() != "darwin":
        raise WarpUnavailable("opening in Warp is supported on macOS only")
    app = warp_app_path()
    if app is None:
        raise WarpUnavailable(f"{WARP_APP} not found in /Applications or ~/Applications")
    open_cmd = locate_command("open").command
    if not open_cmd:
        raise WarpUnavailable("the macOS `open` command was not found")
    config = write_tab_config(plan, home)
    uri = tab_config_uri(plan.task_id)
    # The URI goes to whichever app owns warp://; naming the bundle covers a missing
    # or stale URL-scheme registration.
    if opener([*open_cmd, uri]) or opener([*open_cmd, "-a", str(app), uri]):
        return config
    raise WarpUnavailable(f"`open {uri}` failed (tab config written to {config})")
