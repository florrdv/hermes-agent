"""Open a kanban card's Claude Code session in Warp (macOS).

Warp's ``warp://action/new_window?path=`` / ``new_tab`` URIs only change directory; they
cannot run a command. A Launch Configuration can: a YAML file under
``~/.warp/launch_configurations/`` whose pane ``layout`` carries an absolute ``cwd`` and
``commands: [{exec: ...}]``, opened with ``warp://launch/<launch_configuration_path>``
(https://docs.warp.dev/terminal/sessions/launch-configurations,
https://docs.warp.dev/terminal/more-features/uri-scheme). Hermes writes one file per task,
``hermes-<task_id>.yaml``, overwritten on every open.

Every YAML scalar is emitted as a JSON string, which YAML reads as a double-quoted scalar,
so paths and shell-quoted commands cannot break the document.
"""

from __future__ import annotations

import json
import re
import subprocess
from pathlib import Path
from typing import Callable, Optional, Sequence
from urllib.parse import quote

from hermes_cli.kanban_claude_session import OpenSessionPlan

WARP_APP = "Warp.app"


class WarpUnavailable(RuntimeError):
    """Warp cannot be launched on this host (not macOS, not installed, or ``open`` failed)."""


def launch_configurations_dir(home: Optional[Path] = None) -> Path:
    return (home or Path.home()) / ".warp" / "launch_configurations"


def launch_config_path(task_id: str, home: Optional[Path] = None) -> Path:
    safe = re.sub(r"[^A-Za-z0-9_.-]", "_", task_id)
    return launch_configurations_dir(home) / f"hermes-{safe}.yaml"


def launch_config_yaml(plan: OpenSessionPlan, home: Optional[Path] = None) -> str:
    """One window, one tab, one pane that runs ``plan.command`` in ``plan.cwd`` (Warp wants an
    absolute ``cwd``; a plan without one opens in the user's home)."""
    q = json.dumps
    cwd = plan.cwd or str(home or Path.home())
    return "\n".join((
        f"# Generated by `hermes kanban open-session {plan.task_id}` ({plan.mode}); overwritten on every open.",
        "---",
        f"name: {q(f'Hermes {plan.task_id}')}",
        "windows:",
        "  - tabs:",
        f"      - title: {q(f'{plan.task_id} ({plan.mode})')}",
        "        layout:",
        f"          cwd: {q(cwd)}",
        "          commands:",
        f"            - exec: {q(plan.command)}",
        "",
    ))


def write_launch_config(plan: OpenSessionPlan, home: Optional[Path] = None) -> Path:
    path = launch_config_path(plan.task_id, home)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(launch_config_yaml(plan, home), encoding="utf-8")
    return path


def launch_uri(config_path: Path) -> str:
    return "warp://launch/" + quote(str(config_path), safe="/")


def warp_app_path() -> Optional[Path]:
    from hermes_platform.resolver.known_dirs import mac_application_dirs

    for base in mac_application_dirs():
        candidate = Path(base).expanduser() / WARP_APP
        if candidate.is_dir():
            return candidate
    return None


def _run_open(argv: Sequence[str]) -> bool:
    try:
        return subprocess.run(list(argv), capture_output=True, timeout=15, check=False).returncode == 0
    except (OSError, subprocess.SubprocessError):
        return False


def launch_in_warp(plan: OpenSessionPlan, *, opener: Callable[[Sequence[str]], bool] = _run_open,
                   home: Optional[Path] = None) -> Path:
    """Write the task's launch configuration and ask macOS to open it in Warp; returns the
    config path. ``opener(argv) -> ok`` is the only process boundary (tests inject it)."""
    from hermes_platform.host.facts import os_family
    from hermes_platform.resolver import locate_command

    if os_family() != "darwin":
        raise WarpUnavailable("opening in Warp is supported on macOS only")
    app = warp_app_path()
    if app is None:
        raise WarpUnavailable(f"{WARP_APP} not found in /Applications or ~/Applications")
    open_cmd = locate_command("open").command
    if not open_cmd:
        raise WarpUnavailable("the macOS `open` command was not found")
    config = write_launch_config(plan, home)
    uri = launch_uri(config)
    # The URI goes to whichever app owns warp://; naming the bundle covers a missing
    # or stale URL-scheme registration.
    if opener([*open_cmd, uri]) or opener([*open_cmd, "-a", str(app), uri]):
        return config
    raise WarpUnavailable(f"`open {uri}` failed (launch configuration written to {config})")
